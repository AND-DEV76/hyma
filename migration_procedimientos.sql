CREATE TABLE IF NOT EXISTS consulta_procedimiento (
    id_consulta_procedimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_consulta BIGINT NOT NULL,
    id_paciente BIGINT NOT NULL,
    id_procedimiento BIGINT NOT NULL,
    cantidad INT NOT NULL DEFAULT 1,
    precio_unitario NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    subtotal NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    instrucciones TEXT,
    estado VARCHAR(30) NOT NULL DEFAULT 'ESPERA',
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    fecha_atencion TIMESTAMP,
    id_usuario_atendio BIGINT,
    CONSTRAINT fk_cp_consulta FOREIGN KEY (id_consulta) REFERENCES consulta(id_consulta) ON DELETE CASCADE,
    CONSTRAINT fk_cp_paciente FOREIGN KEY (id_paciente) REFERENCES paciente(id_paciente),
    CONSTRAINT fk_cp_procedimiento FOREIGN KEY (id_procedimiento) REFERENCES procedimiento(id_procedimiento),
    CONSTRAINT fk_cp_usuario_atendio FOREIGN KEY (id_usuario_atendio) REFERENCES usuario(id_usuario)
);

CREATE INDEX IF NOT EXISTS idx_cp_consulta ON consulta_procedimiento(id_consulta);
CREATE INDEX IF NOT EXISTS idx_cp_paciente ON consulta_procedimiento(id_paciente);
CREATE INDEX IF NOT EXISTS idx_cp_estado ON consulta_procedimiento(estado);
CREATE INDEX IF NOT EXISTS idx_cp_fecha_registro ON consulta_procedimiento(fecha_registro);
