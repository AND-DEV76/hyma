ALTER TABLE signo_vital ADD COLUMN IF NOT EXISTS fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE signo_vital ALTER COLUMN id_consulta DROP NOT NULL;

UPDATE signo_vital sv
SET id_paciente = c.id_paciente
FROM consulta c
WHERE sv.id_consulta = c.id_consulta
  AND sv.id_paciente IS NULL;

