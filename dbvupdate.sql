CREATE TABLE IF NOT EXISTS cola_atencion (
    id_cola BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_paciente BIGINT NOT NULL REFERENCES paciente(id_paciente),
    fecha_ingreso TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',
    prioridad INT NOT NULL DEFAULT 0,
    fecha_atencion TIMESTAMP,
    CONSTRAINT chk_cola_estado CHECK (estado IN (
        'PENDIENTE', 'EN_PRECONSULTA', 'EN_CONSULTA',
        'EN_FARMACIA', 'FINALIZADO', 'CANCELADO'
    )),
    CONSTRAINT chk_cola_prioridad CHECK (prioridad >= 0)
);

CREATE INDEX IF NOT EXISTS idx_cola_estado ON cola_atencion(estado);
CREATE INDEX IF NOT EXISTS idx_cola_fecha_ingreso ON cola_atencion(fecha_ingreso);
CREATE INDEX IF NOT EXISTS idx_cola_paciente ON cola_atencion(id_paciente);

-- La versión inicial vinculaba los signos únicamente a consulta. Se conserva
-- esa relación para datos históricos y se añade el paciente para preconsulta.
